// Run with Node and Playwright available (Chromium installed).
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const screenshots = process.env.MERA_SCREENSHOT_DIR || fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'mera-keys-'));
fs.mkdirSync(screenshots, { recursive: true });
const server = http.createServer((req, res) => {
  const file = path.resolve(root, '.' + (req.url === '/' ? '/index.html' : req.url.split('?')[0]));
  if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
  const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp', '.json': 'application/json' };
  fs.readFile(file, (error, data) => { res.writeHead(error ? 404 : 200, { 'Content-Type': types[path.extname(file)] || 'application/octet-stream' }); res.end(error ? '' : data); });
});
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true, ...(process.env.MERA_BROWSER_CHANNEL ? { channel: process.env.MERA_BROWSER_CHANNEL } : {}) });
  try {
    const context = await browser.newContext({ locale: 'hu-HU' }); // the site follows the browser language
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = `http://127.0.0.1:${server.address().port}`;
    await page.goto(url);
    const keys = page.locator('.mera-hidden-key');
    const dialog = page.locator('.mera-key-dialog');
    const count = () => page.locator('.mera-key-progress span').textContent();
    const close = () => page.locator('.mera-key-close').click();
    assert.equal(await keys.count(), 5);
    // Key art is lazy-loaded, so bring each key on screen before checking it loaded.
    for (let i = 0; i < 5; i += 1) await keys.nth(i).scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('.mera-hidden-key img')].every(img => img.complete && img.naturalWidth > 0));
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await keys.locator('img').evaluateAll(images => new Set(images.map(img => img.src)).size), 5);
    assert.equal(await count(), '0/5');
    await keys.nth(0).click();
    assert.equal(await count(), '1/5');
    assert.equal(await page.locator('.mera-secret-form').isVisible(), false);
    await page.locator('.mera-key-inspect').click();
    assert.equal(await page.locator('.mera-detail-dialog').isVisible(), true);
    assert.equal(await page.locator('.mera-detail-stage img').getAttribute('src'), 'assets/keys/sofia-sz.webp');
    await page.keyboard.press('Escape');
    assert.equal(await dialog.isVisible(), true);
    assert.equal(await page.locator('.mera-key-inspect').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Escape');
    // The found key fades away, so focus goes to the key counter.
    assert.equal(await page.locator('.mera-key-progress').evaluate(el => el === document.activeElement), true);
    await keys.nth(0).waitFor({ state: 'hidden' });
    assert.equal(await keys.nth(1).isVisible(), true);
    await page.keyboard.press('Enter');
    assert.equal(await count(), '1/5');
    await close();
    await page.reload();
    assert.equal(await count(), '1/5');
    assert.equal(await keys.nth(0).isVisible(), false, 'found keys stay hidden after a reload');
    assert.equal(await keys.nth(0).evaluate(el => getComputedStyle(el).visibility), 'hidden');
    assert.equal(await keys.nth(1).evaluate(el => getComputedStyle(el).animationName), 'mera-key-breathe', 'unfound keys fade in and out');
    for (let i = 1; i < 5; i++) { await keys.nth(i).click(); if (i < 4) await close(); }
    assert.equal(await dialog.locator('.mera-key-emblem .mera-key-art').getAttribute('src'), 'assets/keys/sofia-a.webp');
    assert.equal(await count(), '5/5');
    assert.equal(await dialog.evaluate(el => el.classList.contains('is-discovering')), true);
    assert.equal(await dialog.evaluate(el => el.classList.contains('is-unlocking')), false);
    await page.waitForTimeout(1100);
    assert.equal(await page.locator('.mera-secret-content').isVisible(), true);
    const poem = 'Öt kulcs rejtőzött titkok nyomán,\ns most mind előkerült az út során.\nDe a zár még őriz egy utolsó titkot:\negy nevet, mely egyszer mindent elindított.\nÍrd be a titkos szót, ha sejted már,\ns a kulcsok mögött egy ajándék vár.';
    assert.equal(await page.locator('.mera-secret-poem').textContent(), poem);
    assert.equal(await page.locator('.mera-gift').isVisible(), false);
    assert.equal(await page.locator('.mera-key-gallery button').count(), 5);
    for (let i = 0; i < 5; i++) {
      await page.locator('.mera-key-gallery button').nth(i).click();
      assert.equal(await page.locator('.mera-detail-dialog').isVisible(), true);
      await page.screenshot({path:path.join(screenshots, `mera-detail-${i+1}.png`)});
      await page.locator('.mera-detail-close').click();
      assert.equal(await page.locator('.mera-key-gallery button').nth(i).evaluate(el => el === document.activeElement), true);
    }
    await page.waitForFunction(() => [...document.querySelectorAll('.mera-real-lock img')].every(img => img.complete && img.naturalWidth > 0));
    await dialog.evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: path.join(screenshots, 'mera-code-poem.png') });
    const input = page.locator('#mera-secret-word');
    const submit = page.locator('.mera-secret-form button');
    await submit.click();
    assert.equal(await page.locator('#mera-secret-error').textContent(), 'Írd be a titkos szót.');
    await input.fill('wrong');
    await input.press('Enter');
    assert.equal(await input.getAttribute('aria-invalid'), 'true');
    assert.equal(await page.locator('.mera-gift').isVisible(), false);
    await input.fill('  Szófia  ');
    assert.equal(await input.getAttribute('aria-invalid'), 'false');
    await input.press('Enter');
    assert.equal(await page.locator('.mera-gift').isVisible(), true);
    assert.equal(await page.locator('.mera-gift-code').textContent(), 'SZOFIA');
    assert.equal(await input.isVisible(), false);
    assert.equal(await dialog.evaluate(el => el.classList.contains('is-unlocking')), true);
    await page.waitForTimeout(2100);
    assert.equal(await page.locator('.mera-lock-open').evaluate(el => getComputedStyle(el).opacity), '1');
    await page.screenshot({ path: path.join(screenshots, 'mera-unlocked.png') });
    await close();
    await page.reload();
    assert.equal(await dialog.isVisible(), false);
    await page.locator('.mera-key-progress').click();
    assert.equal(await page.locator('.mera-secret-content').isVisible(), true);
    assert.equal(await page.locator('.mera-gift').isVisible(), true);
    assert.equal(await dialog.evaluate(el => el.classList.contains('is-unlocking')), false);
    await close();
    await page.selectOption('#language', 'en');
    await page.locator('.mera-key-progress').click();
    assert.equal(await page.locator('#mera-secret-title').textContent(), 'Secret MERA');
    await close();
    await page.selectOption('#language', 'de');
    await page.locator('.mera-key-progress').click();
    assert.equal(await page.locator('#mera-secret-title').textContent(), 'Das geheime MERA');
    await close();
    const second = await context.newPage();
    await second.goto(url);
    await second.evaluate(() => localStorage.setItem('mera-secret-keys-v1', '["story","invalid","story"]'));
    await page.waitForFunction(() => document.querySelector('.mera-key-progress span').textContent === '1/5');
    await second.close();
    await page.evaluate(() => { localStorage.setItem('mera-secret-keys-v1', '{broken'); localStorage.removeItem('mera-secret-word-v1'); });
    await page.reload();
    assert.equal(await count(), '0/5');
    await page.setViewportSize({ width: 375, height: 812 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    for (let i = 0; i < 5; i++) {
      const box = await keys.nth(i).boundingBox();
      assert.ok(box.width >= 44 && box.height >= 44);
      await keys.nth(i).click();
      assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true);
      if (i < 4) await close();
    }
    assert.equal(await page.locator('.mera-secret-content').evaluate(el => getComputedStyle(el).animationName), 'none');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await input.isVisible(), true);
    await page.screenshot({ path: path.join(screenshots, 'mera-mobile.png') });
    await page.locator('.mera-key-gallery button').nth(3).click();
    assert.equal(await page.locator('.mera-detail-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true);
    await page.screenshot({path:path.join(screenshots, 'mera-detail-mobile.png')});
    await page.locator('.mera-detail-close').click();
    await input.fill('szofia');
    await input.press('Enter');
    assert.equal(await page.locator('.mera-gift').isVisible(), true);
    assert.equal(await page.locator('.mera-gift').evaluate(el => getComputedStyle(el).animationName), 'none');
    await close();
    assert.equal(await keys.nth(0).isVisible(), false, 'all found keys are hidden');
    await page.evaluate(() => localStorage.removeItem('mera-secret-keys-v1'));
    await page.reload();
    await keys.nth(0).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(screenshots, 'mera-mobile-key.png') });
    const blocked = await browser.newContext({ locale: 'hu-HU' });
    await blocked.addInitScript(() => { Storage.prototype.getItem = Storage.prototype.setItem = () => { throw new DOMException('Blocked', 'SecurityError'); }; });
    const noStorage = await blocked.newPage();
    await noStorage.goto(url);
    await noStorage.locator('.mera-hidden-key').first().click();
    assert.equal(await noStorage.locator('.mera-key-progress span').textContent(), '1/5');
    assert.ok((await noStorage.locator('.mera-key-storage').textContent()).length > 0);
    await noStorage.locator('.mera-key-close').click();
    for (let i = 1; i < 5; i++) { await noStorage.locator('.mera-hidden-key').nth(i).click(); if (i < 4) await noStorage.locator('.mera-key-close').click(); }
    await noStorage.locator('#mera-secret-word').fill('SZOFIA');
    await noStorage.locator('.mera-secret-form button').click();
    assert.equal(await noStorage.locator('.mera-gift-code').textContent(), 'SZOFIA');
    assert.deepEqual(errors, []);
    console.log('PASS: keys, persistence, exact Hungarian poem, form gated at 5/5, empty/wrong answers, accented/case-insensitive answer, Enter submit, gift code, solved reload, unlock/reopen, languages, storage edge cases, mobile, reduced motion, no browser errors.');
  } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); server.close(); process.exitCode = 1; });
