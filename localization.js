const languagePicker = document.querySelector('#language');

function translate(dictionary, key) {
  const value = dictionary[key];
  if (typeof value !== 'string') throw new Error(`Missing translation: ${key}`);
  return value;
}

function applyLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = translate(dictionary, element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    element.setAttribute('content', translate(dictionary, element.dataset.i18nContent));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', translate(dictionary, element.dataset.i18nAlt));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', translate(dictionary, element.dataset.i18nAriaLabel));
  });
  document.title = translate(dictionary, document.querySelector('title').dataset.i18n);
  if (languagePicker) languagePicker.value = language;
  document.dispatchEvent(new CustomEvent('mera:languagechange', { detail: { language } }));
}

let savedLanguage;
try {
  savedLanguage = localStorage.getItem('mera-language');
} catch (error) {
  console.warn('Could not read the saved language preference.', error);
}
applyLanguage(translations[savedLanguage] ? savedLanguage : 'hu');

languagePicker?.addEventListener('change', () => {
  applyLanguage(languagePicker.value);
  try {
    localStorage.setItem('mera-language', languagePicker.value);
  } catch (error) {
    console.warn('Could not save the language preference.', error);
  }
});
